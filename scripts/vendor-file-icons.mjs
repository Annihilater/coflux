#!/usr/bin/env node
// Vendors the file and folder icons of the desktop changes view (plan 20261001-changes-review-polish)
// from a pinned Catppuccin VS Code Icons release. The output is committed: builds and CI never
// fetch it. Re-run to upgrade (change TAG) or to reproduce the committed copy:
//
//   node scripts/vendor-file-icons.mjs
//
// Needs network and an authenticated `gh` CLI, plus `unzip`.
//
// What it takes from the release VSIX:
// - extension/dist/unflavored/*.svg — every icon, colours as `var(--vscode-ctp-*)` CSS variables,
//   which the renderer stylesheet defines against our palette;
// - extension/dist/mocha/theme.json — only its mapping tables (fileNames, fileExtensions,
//   folderNames, folderNamesExpanded) and the default file / folder / open-folder icons. Its
//   iconDefinitions paths are flavour-relative, so each icon is resolved by name onto unflavored/;
// - extension/LICENSE.txt — MIT, kept next to the icons.
//
// Output, under apps/desktop/src/renderer/assets/file-icons/: icons/<name>.svg byte for byte,
// LICENSE, and mapping.ts (sorted keys, so a re-run reproduces it exactly).

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, dirname, join, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = "catppuccin/vscode-icons";
const TAG = "v1.26.0";
const ASSET = `catppuccin-vsc-icons-${TAG.slice(1)}.vsix`;

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "apps", "desktop", "src", "renderer", "assets", "file-icons");
const iconsOut = join(outDir, "icons");

function fail(message) {
  console.error(`vendor-file-icons: ${message}`);
  process.exit(1);
}

const work = mkdtempSync(join(tmpdir(), "coflux-file-icons-"));
try {
  execFileSync("gh", ["release", "download", TAG, "-R", REPO, "-p", ASSET, "-D", work], { stdio: "inherit" });
  const vsix = join(work, ASSET);
  if (!existsSync(vsix)) fail(`${ASSET} was not downloaded`);
  const unpacked = join(work, "vsix");
  execFileSync(
    "unzip",
    ["-q", vsix, "extension/dist/unflavored/*", "extension/dist/mocha/theme.json", "extension/LICENSE.txt", "-d", unpacked],
    { stdio: "inherit" },
  );

  const unflavored = join(unpacked, "extension", "dist", "unflavored");
  const theme = JSON.parse(readFileSync(join(unpacked, "extension", "dist", "mocha", "theme.json"), "utf8"));
  const available = new Set(
    readdirSync(unflavored)
      .filter((file) => file.endsWith(".svg"))
      .map((file) => file.slice(0, -".svg".length)),
  );
  if (available.size === 0) fail("the release ships no unflavored SVGs");

  /** An iconDefinitions id → the unflavored icon of the same file name. */
  const iconName = (id) => {
    const definition = theme.iconDefinitions?.[id];
    if (!definition?.iconPath) fail(`icon definition ${id} has no iconPath`);
    const name = basename(definition.iconPath, ".svg");
    if (!available.has(name)) fail(`icon ${name} (definition ${id}) is missing from unflavored/`);
    return name;
  };
  const table = (key) => {
    const source = theme[key];
    if (!source || typeof source !== "object") fail(`theme.json has no ${key} table`);
    const entries = Object.keys(source)
      .sort()
      .map((name) => [name.toLowerCase(), iconName(source[name])]);
    return Object.fromEntries(entries);
  };

  const mapping = {
    file: iconName(theme.file),
    folder: iconName(theme.folder),
    folderExpanded: iconName(theme.folderExpanded),
    fileNames: table("fileNames"),
    fileExtensions: table("fileExtensions"),
    folderNames: table("folderNames"),
    folderNamesExpanded: table("folderNamesExpanded"),
  };

  // Replace the vendored icons wholesale so an upgrade drops icons the release no longer ships.
  // The path is a constant under this repository, never a computed or empty value.
  if (!iconsOut.endsWith(`${sep}renderer${sep}assets${sep}file-icons${sep}icons`)) fail(`unexpected output path ${iconsOut}`);
  rmSync(iconsOut, { recursive: true, force: true });
  mkdirSync(iconsOut, { recursive: true });
  for (const name of [...available].sort()) copyFileSync(join(unflavored, `${name}.svg`), join(iconsOut, `${name}.svg`));
  copyFileSync(join(unpacked, "extension", "LICENSE.txt"), join(outDir, "LICENSE"));

  const literal = (value) => JSON.stringify(value, null, 2);
  const module = `// Generated by scripts/vendor-file-icons.mjs from ${REPO} ${TAG} (MIT, see ./LICENSE).
// Do not edit by hand: re-run the script. Keys are lower-cased; values are icon names in ./icons/.

export const ICON_SET = ${literal(`${REPO}@${TAG}`)};
export const DEFAULT_FILE_ICON = ${literal(mapping.file)};
export const DEFAULT_FOLDER_ICON = ${literal(mapping.folder)};
export const DEFAULT_FOLDER_OPEN_ICON = ${literal(mapping.folderExpanded)};

export const FILE_NAMES: Readonly<Record<string, string>> = ${literal(mapping.fileNames)};

export const FILE_EXTENSIONS: Readonly<Record<string, string>> = ${literal(mapping.fileExtensions)};

export const FOLDER_NAMES: Readonly<Record<string, string>> = ${literal(mapping.folderNames)};

export const FOLDER_NAMES_EXPANDED: Readonly<Record<string, string>> = ${literal(mapping.folderNamesExpanded)};
`;
  writeFileSync(join(outDir, "mapping.ts"), module);
  console.log(`vendor-file-icons: ${available.size} icons from ${REPO} ${TAG} → ${outDir}`);
} finally {
  // `work` is the mkdtemp result, never empty.
  if (work && work.startsWith(join(tmpdir(), "coflux-file-icons-"))) rmSync(work, { recursive: true, force: true });
}
